create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (username ~ '^[a-zA-Z0-9_]{3,24}$'),
  display_name text not null check (char_length(display_name) between 2 and 60),
  bio text not null default '' check (char_length(bio) <= 300),
  avatar_url text,
  role public.user_role not null default 'member',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.genres (
  id bigint generated by default as identity primary key,
  name text unique not null, slug text unique not null
);

create table public.bands (
  id uuid primary key default gen_random_uuid(),
  name text not null, slug text unique not null,
  summary text not null, biography text not null default '',
  formed_year int check (formed_year between 1900 and 2100),
  ended_year int check (ended_year is null or ended_year >= formed_year),
  country_code char(2), image_url text, website_url text,
  musicbrainz_id uuid unique, wikidata_id text unique,
  published boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.band_genres (
  band_id uuid references public.bands(id) on delete cascade,
  genre_id bigint references public.genres(id) on delete cascade,
  primary key (band_id, genre_id)
);

create table public.places (
  id uuid primary key default gen_random_uuid(),
  name text not null, city text not null, country_code char(2) not null,
  kind public.place_kind not null,
  location extensions.geography(point, 4326) not null,
  description text not null default '', website_url text,
  created_at timestamptz not null default now()
);
create index places_location_idx on public.places using gist(location);

create table public.band_places (
  band_id uuid references public.bands(id) on delete cascade,
  place_id uuid references public.places(id) on delete cascade,
  relationship text not null,
  primary key (band_id, place_id, relationship)
);

create table public.favorites (
  user_id uuid references public.profiles(id) on delete cascade,
  band_id uuid references public.bands(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, band_id)
);

create table private.migration_log (
  id bigint generated always as identity primary key,
  source_file text not null, source_key text not null,
  target_table text not null, target_id text,
  imported_at timestamptz not null default now(),
  unique(source_file, source_key, target_table)
);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, username, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'username', 'rocker_' || left(new.id::text, 8)), coalesce(new.raw_user_meta_data->>'display_name', 'Nuevo integrante'));
  return new;
end; $$;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
